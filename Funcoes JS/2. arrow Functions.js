a = 2
b = 3
const somar = (a, b) => {
    return a + b
}

// Arrow functios...
const subtrair = (a, b) => a - b
const Multiplicar = (a, b) => a * b
const dividir = (a, b) => a / b

const soma = somar(2, 3)
const subtraçao = subtrair(2, 3)
const Multiplicaçao = Multiplicar(2, 3)
const divisao = dividir(2, 3)

// Exibindo resultados
console.log(`Soma: ${soma}`)
console.log(`subtraçao: ${subtraçao}`)
console.log(`Multiplicaçao: ${Multiplicaçao}`)
console.log(`divisao: ${divisao}`)